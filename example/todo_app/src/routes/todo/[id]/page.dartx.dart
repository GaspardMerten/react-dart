/// Fetches this route's data before the page renders. The generator picks it up
/// by name, so there is nothing to register.
Future<Todo> loader(LoaderContext context) => fetchTodo(context.params['id']!);

/// With these two, the server's fetch travels to the browser inside the page
/// and the client does not repeat it. Delete them and everything still works —
/// the client just loads it again.
Object? encode(Object? todo) => encodeTodo(todo! as Todo);
Object? decode(Object? json) => decodeTodo(json! as Map<String, Object?>);

