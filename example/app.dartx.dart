/// A classic counter.
Component Counter() {
  final (count, setCount) = useState(0);

  return h('section', <String, Object?>{'class': 'counter'}, <Object?>[
h('h2', const <String, Object?>{}, <Object?>['Counter']), 
h('p', const <String, Object?>{}, <Object?>['Value: ', h('strong', const <String, Object?>{}, <Object?>[count])]), 
