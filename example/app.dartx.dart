}

/// A controlled-input todo list. Shows keyed list reconciliation.
Component Todos() {
  final (items, setItems) = useState<List<String>>(const ['Learn reactx']);
  final (draft, setDraft) = useState('');

  void add() {
    if (draft.trim().isEmpty) return;
    setItems([...items, draft.trim()]);
    setDraft('');
  }

  return h('section', <String, Object?>{'class': 'todos'}, <Object?>[
h('h2', const <String, Object?>{}, <Object?>['Todos (', items.length, ')']), 
h('ul', const <String, Object?>{}, <Object?>[
([for (final (i, item) in items.indexed) h('li', <String, Object?>{'key': i}, <Object?>[item])])]
), 
h('input', <String, Object?>{'value': draft, 'onInput': (onValue(setDraft)), 'placeholder': 'Add a todo'}, const <Object?>[]), 
h('button', <String, Object?>{'onClick': add}, <Object?>['Add'])]
);
}

